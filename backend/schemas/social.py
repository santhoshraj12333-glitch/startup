"""
Pydantic models for the unified social post schema and processed event schema.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, validator


class SocialPost(BaseModel):
    """Unified JSON schema for a raw social media post.

    All fields are optional except ``source`` and ``source_post_id`` which together
    uniquely identify the record. Timestamps are stored as ISO‑8601 strings.
    """

    source: str = Field(..., description="Source identifier, e.g. 'google_news', 'youtube', etc.")
    source_post_id: str = Field(..., description="Unique post identifier within the source")
    text: Optional[str] = None
    published_at: Optional[datetime] = None
    url: Optional[str] = None
    author_id: Optional[str] = None
    language: Optional[str] = None
    collection_timestamp: Optional[datetime] = None
    location_id: Optional[int] = None
    resolved_status: Optional[str] = None  # resolved / ambiguous / unresolved

    @validator("published_at", "collection_timestamp", pre=True)
    def parse_dt(cls, v: Any) -> Optional[datetime]:
        if isinstance(v, str):
            try:
                return datetime.fromisoformat(v)
            except Exception:
                return None
        return v


class ProcessedEvent(BaseModel):
    """Schema for an event returned by Person 2's NLP service.

    ``event_id`` is the unique identifier generated by the NLP pipeline. The
    ``normalized_post_id`` foreign key is added by the backend when persisting the
    event.
    """

    event_id: str
    source_post_id: str
    event_type: str
    severity: Optional[str] = None
    confidence: Optional[float] = None
    location_id: Optional[int] = None
    details: Optional[Dict[str, Any]] = None
    processed_at: Optional[datetime] = None

    @validator("processed_at", pre=True)
    def parse_dt(cls, v: Any) -> Optional[datetime]:
        if isinstance(v, str):
            try:
                return datetime.fromisoformat(v)
            except Exception:
                return None
        return v

